<script>
document.addEventListener("DOMContentLoaded", () => {

    // --- Tab Switching Logic ---
    const tabBtns = document.querySelectorAll('.sd-tab-btn');
    const grids = document.querySelectorAll('.sd-grid-wrapper');
    const descs = document.querySelectorAll('.sd-tab-desc-item');

    tabBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const target = btn.getAttribute('data-target');

            // 1. Update Active Button State
            tabBtns.forEach(b => b.classList.remove('sd-tab-active'));
            btn.classList.add('sd-tab-active');

            // 2. Update Description
            descs.forEach(desc => {
                if (desc.id === 'desc-' + target) {
                    desc.classList.add('sd-active-desc');
                } else {
                    desc.classList.remove('sd-active-desc');
                }
            });

            // 3. Update Grid and Trigger Re-animation
            grids.forEach(grid => {
                if (grid.id === 'grid-' + target) {
                    grid.classList.add('sd-active-grid');
                    
                    // Force reflow and re-trigger entry animations for cards
                    const cards = grid.querySelectorAll('.sd-card');
                    cards.forEach(card => {
                        card.classList.remove('sd-card-in');
                        void card.offsetWidth; // trigger reflow
                        card.classList.add('sd-card-in');
                    });
                } else {
                    grid.classList.remove('sd-active-grid');
                }
            });
        });
    });

    // --- Number Counter Logic ---
    const counterObserver = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const counter = entry.target;
                const target = +counter.getAttribute('data-target');
                const duration = 2000; // Animation duration in ms (2 seconds)
                const increment = target / (duration / 16); // Approx 60 frames per second
                let current = 0;
                
                const updateCounter = () => {
                    current += increment;
                    if (current < target) {
                        counter.innerText = Math.ceil(current);
                        requestAnimationFrame(updateCounter);
                    } else {
                        counter.innerText = target;
                    }
                };
                setTimeout(updateCounter, 800);
                observer.unobserve(counter); // Stop observing once animated
            }
        });
    }, { threshold: 0.5 });
    document.querySelectorAll(".counter").forEach(el => counterObserver.observe(el));
});
</script>